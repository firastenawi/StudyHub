def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in STRINGS else "en"


def language() -> str:
    return _lang


def is_rtl() -> bool:
    return _lang == "ar"


def tr_in(lang: str, key: str, **kwargs) -> str:
    text = STRINGS.get(lang, {}).get(key) or STRINGS["en"].get(key) or key
    return text.format(**kwargs) if kwargs else text


def tr(key: str, **kwargs) -> str:
    return tr_in(_lang, key, **kwargs)


def greeting_key(hour: int) -> str:
    if 5 <= hour < 12:
        return "greet_morning"
    if 12 <= hour < 17:
        return "greet_afternoon"
    if 17 <= hour < 23:
        return "greet_evening"
    return "greet_night"


_AR_DAYS = ["الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت", "الأحد"]
# Levantine month names (as used in Syria)
_AR_MONTHS = ["كانون الثاني", "شباط", "آذار", "نيسان", "أيار", "حزيران",
              "تموز", "آب", "أيلول", "تشرين الأول", "تشرين الثاني", "كانون الأول"]


_AR_DAYS_SHORT = ["اثنين", "ثلاثاء", "أربعاء", "خميس", "جمعة", "سبت", "أحد"]
_EN_DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def day_name(day: int, short: bool = False) -> str:
    """day: 0 = Monday ... 6 = Sunday (Python weekday())."""
    if _lang == "ar":
        return (_AR_DAYS_SHORT if short else _AR_DAYS)[day % 7]
    name = _EN_DAYS[day % 7]
    return name[:3] if short else name


_clock12 = True  # 12-hour clock by default (changeable in Settings)


def set_clock_format(twelve_hours: bool) -> None:
    global _clock12
    _clock12 = bool(twelve_hours)


def uses_12h() -> bool:
    return _clock12


def meridiem(hour: int) -> str:
    """ص / م  or  AM / PM"""
    return tr("time_am") if hour < 12 else tr("time_pm")


def format_hm(hour: int, minute: int, suffix: bool = True) -> str:
    """9:05 م / 9:05 PM in 12-hour mode, 21:05 in 24-hour mode."""
    if not _clock12:
        return f"{hour:02d}:{minute:02d}"
    text = f"{hour % 12 or 12}:{minute:02d}"
    return f"{text} {meridiem(hour)}" if suffix else text


def format_hhmm(value: str, suffix: bool = True) -> str:
    """'14:30' (as stored in the database) -> '2:30 م'."""
    try:
        h, m = value.split(":")[:2]
        return format_hm(int(h), int(m), suffix)
    except (ValueError, AttributeError):
        return value or ""


def format_range(start: str, end: str) -> str:
    return ltr(f"{format_hhmm(start)} – {format_hhmm(end)}")


def ltr(text: str) -> str:
    """Keeps times/dates like '10:00–11:30' or '2026-10-23' in order inside Arabic text
    (Unicode left-to-right isolate)."""
    return f"⁦{text}⁩"


def ordered_days(week_start: int) -> list[int]:
    """The 7 weekdays starting from `week_start` (e.g. 5 = Saturday first)."""
    return [(week_start + i) % 7 for i in range(7)]


def format_long_date(d: date) -> str:
    if _lang == "ar":
        return f"{_AR_DAYS[d.weekday()]}، {d.day} {_AR_MONTHS[d.month - 1]} {d.year}"
    return d.strftime("%A, %B ") + f"{d.day}, {d.year}"


def relative_time(stamp: str) -> str:
    """'2026-10-24 21:40:00' -> 'من 5 د' / '5 min ago'."""
    try:
        then = datetime.strptime(stamp, "%Y-%m-%d %H:%M:%S")
    except (TypeError, ValueError):
        return stamp or ""
    minutes = int((datetime.now() - then).total_seconds() // 60)
    if minutes < 1:
        return tr("time_just_now")
    if minutes < 60:
        return tr("time_minutes", n=minutes)
    if then.date() == datetime.now().date():
        return tr("time_hours", n=minutes // 60)
    if (datetime.now().date() - then.date()).days == 1:
        return tr("time_yesterday")
    return ltr(then.strftime("%Y-%m-%d"))


